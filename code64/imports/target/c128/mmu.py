"""The registers of the MMU."""

MMU_CONFIGURATION      = 0xd500
MMU_PRECONFIGURATION_A = 0xd501
MMU_PRECONFIGURATION_B = 0xd502
MMU_PRECONFIGURATION_C = 0xd503
MMU_PRECONFIGURATION_D = 0xd504
MMU_MODE               = 0xd505 # bit 7: 40/80 columns key, read only
MMU_RAM_CONFIGURATION  = 0xd506
MMU_ZERO_PAGE_LO       = 0xd507
MMU_ZERO_PAGE_HI       = 0xd508
MMU_STACK_PAGE_LO      = 0xd509
MMU_STACK_PAGE_HI      = 0xd50a
MMU_VERSION            = 0xd50b
